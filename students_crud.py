# CRUD in PostgreSQL on students table

import sys
import psycopg


def connect():
    # connection info for the database. These parameters must match the PostgreSQL configuration
    return psycopg.connect(host="localhost", dbname="school", user="postgres", password="postgres")


def getAllStudents():
    # fetches the student records from the database table and prints them
    conn = connect()
    cur = conn.cursor()
    cur.execute("SELECT * FROM students ORDER BY student_id")
    rows = cur.fetchall()

    print("student_id | first_name | last_name | email | enrollment_date")
    for row in rows:
        student_id, first_name, last_name, email, enrollment_date = row
        print(student_id, "|", first_name, "|", last_name, "|", email, "|", enrollment_date)

    conn.close()


def addStudent(first_name, last_name, email, enrollment_date):
    # adds a new student, and student_id will be auto-generated by the database
    conn = connect()
    cur = conn.cursor()
    cur.execute("INSERT INTO students (first_name, last_name, email, enrollment_date) VALUES (%s, %s, %s, %s)", (first_name, last_name, email, enrollment_date))
    # commits the changes
    conn.commit()
    conn.close()
    print("Student added.")


def updateStudentEmail(student_id, new_email):
    # updates the email value for the student with that id
    conn = connect()
    cur = conn.cursor()
    cur.execute("UPDATE students SET email = %s WHERE student_id = %s", (new_email, student_id))
    conn.commit()
    conn.close()

    # shows how many rows have been affected by the action (0 means that no student with that id exists)
    if cur.rowcount == 0:
        print("No student found with id", student_id)
    else:
        print("Email updated.")


def deleteStudent(student_id):
    # deletes the student with the given student_id
    conn = connect()
    cur = conn.cursor()
    cur.execute("DELETE FROM students WHERE student_id = %s", (student_id,))
    conn.commit()
    conn.close()

    if cur.rowcount == 0:
        print("No student found with id", student_id)
    else:
        print("Student deleted.")


def main():
    # takes the command line arguments and calls the appropriate function according to the arguments it received
    args = sys.argv[1:]
    if len(args) == 0:
        print("Commands: list, add, update-email, delete")
        return

    command = args[0]

    try:
        if command == "list" and len(args) == 1:
            getAllStudents()
        elif command == "add" and len(args) == 5:
            addStudent(args[1], args[2], args[3], args[4])
        elif command == "update-email" and len(args) == 3:
            updateStudentEmail(int(args[1]), args[2])
        elif command == "delete" and len(args) == 2:
            deleteStudent(int(args[1]))
        else:
            print("Commands: list, add, update-email, delete")
    except ValueError:
        # when student_id is not a number
        print("Error: student_id must be a number.")
    except psycopg.Error as error:
        # if theres a database error
        print("Database error:", error)


main()
